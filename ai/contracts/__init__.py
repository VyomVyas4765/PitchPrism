"""Shared domain contracts for the worker (D-03), generated from packages/contracts/schemas.

Types live in generated.py and the bundled JSON Schema in domain.schema.json; both are regenerated by
`pnpm contracts:generate` and must not be edited by hand. Validate JSON-form payloads (ObjectIds and
datetimes as strings) before writing them, for example a StageEvent:

    from ai.contracts import validate
    validate("StageEvent", event)
"""
import json
from functools import lru_cache
from pathlib import Path

from jsonschema import Draft7Validator, FormatChecker

from .generated import *  # noqa: F401,F403 - re-export generated types
from .generated import COLLECTIONS

_SCHEMA_PATH = Path(__file__).with_name("domain.schema.json")
_FORMATS = FormatChecker()


@_FORMATS.checks("objectid")
def _is_object_id(value):
    return not isinstance(value, str) or (len(value) == 24 and all(c in "0123456789abcdefABCDEF" for c in value))


@lru_cache(maxsize=1)
def bundle():
    return json.loads(_SCHEMA_PATH.read_text(encoding="utf-8"))


@lru_cache(maxsize=None)
def _validator(name):
    definitions = bundle()["definitions"]
    if name not in definitions:
        raise KeyError(f"Unknown contract: {name}")
    return Draft7Validator({"$ref": f"#/definitions/{name}", "definitions": definitions}, format_checker=_FORMATS)


def errors(name, document):
    """Return readable validation errors (empty when valid). Messages name paths, never values."""
    return [f"{'/'.join(map(str, error.absolute_path)) or '<root>'}: {error.validator} failed"
            for error in _validator(name).iter_errors(document)]


def validate(name, document):
    problems = errors(name, document)
    if problems:
        raise ValueError(f"{name} does not match the contract: " + "; ".join(problems[:5]))
    return document


__all__ = ["COLLECTIONS", "bundle", "errors", "validate"]
