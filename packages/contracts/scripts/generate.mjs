// Generates every contract artifact from the JSON Schemas (D-03). Run `pnpm contracts:generate`; commit the outputs.
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { compile } from 'json-schema-to-typescript';

const root = new URL('../', import.meta.url);
const read = async path => JSON.parse(await readFile(new URL(path, root), 'utf8'));
const write = async (path, text) => { const url = new URL(path, root); await mkdir(new URL('.', url), { recursive: true }); await writeFile(url, text); };

// ---- Auth contract (unchanged outputs) ----
const session = await read('schemas/session-user.json');
await write('src/generated.ts', await compile(session, 'SessionUser'));
await write('src/roles.ts', `// Generated from schemas/session-user.json. Do not edit.\nexport const ROLES = ${JSON.stringify(session.definitions.Role.enum)} as const;\nexport const ORG_TYPES = ${JSON.stringify(session.definitions.OrgType.enum)} as const;\n`);

// Dev 2 centre input contract (CentreExtractedInput).
const centre = await read('schemas/centre-extracted-input.json');
await write('src/centre-generated.ts', await compile(centre, 'CentreExtractedInput'));

// ---- Domain bundle: one schema, all refs internal (#/definitions/Name) ----
const files = (await readdir(new URL('schemas/domain/', root))).filter(name => name.endsWith('.json')).sort();
const loaded = await Promise.all(files.map(async file => [file, await read(`schemas/domain/${file}`)]));
const titleOf = Object.fromEntries(loaded.map(([file, schema]) => [file, schema.title]));
const definitions = { Role: session.definitions.Role, OrgType: session.definitions.OrgType };
const collections = {};

function rewrite(node) {
  if (Array.isArray(node)) return node.map(rewrite);
  if (!node || typeof node !== 'object') return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === '$ref') {
      const [file, pointer] = value.split('#');
      const name = pointer ? pointer.replace('/definitions/', '') : titleOf[file.replace('../', '')];
      if (!name) throw new Error(`Unresolvable $ref ${value}`);
      out.$ref = `#/definitions/${name}`;
    } else out[key] = rewrite(value);
  }
  return out;
}
function add(name, schema, source) {
  if (definitions[name]) throw new Error(`Duplicate definition ${name} (${source})`);
  definitions[name] = rewrite(schema);
}
for (const [file, schema] of loaded) {
  const { $schema, definitions: local = {}, ...rest } = schema;
  for (const [name, def] of Object.entries(local)) add(name, def, file);
  if (file !== 'common.json') add(schema.title, rest, file);
  if (schema['x-collection']) collections[schema.title] = schema['x-collection'];
}
for (const value of Object.values(definitions)) JSON.stringify(value, (key, v) => {
  if (key === '$ref' && !definitions[v.replace('#/definitions/', '')]) throw new Error(`Missing definition for ${v}`);
  return v;
});
const bundle = { $schema: 'http://json-schema.org/draft-07/schema#', $id: 'https://pitchprism.local/schemas/domain.json', title: 'PitchPrismDomain', definitions };
const banner = '// Generated by packages/contracts/scripts/generate.mjs from schemas/. Do not edit.\n';

// TypeScript types. Role/OrgType come from the auth contract to avoid duplicate exports. A $ref with sibling
// keywords (descriptions) would make the compiler mint a numbered alias (ObjectId1...), so keep the bare $ref.
function forTypescript(node) {
  if (Array.isArray(node)) return node.map(forTypescript);
  if (!node || typeof node !== 'object') return node;
  if (node.$ref === '#/definitions/Role') return { tsType: 'Role' };
  if (node.$ref === '#/definitions/OrgType') return { tsType: 'OrgType' };
  if (node.$ref) return { $ref: node.$ref };
  return Object.fromEntries(Object.entries(node).map(([key, value]) => [key, forTypescript(value)]));
}
const forTs = forTypescript(structuredClone(bundle));
delete forTs.definitions.Role;
delete forTs.definitions.OrgType;
forTs.type = 'object';
forTs.additionalProperties = false;
forTs.properties = Object.fromEntries(Object.keys(collections).map(name => [name, { $ref: `#/definitions/${name}` }]));
const ts = await compile(forTs, 'PitchPrismDomain', { bannerComment: '', unreachableDefinitions: true, additionalProperties: false, strictIndexSignatures: false });
await write('src/domain.generated.ts', `${banner}import type { OrgType, Role } from './generated.js';\n\n${ts}`);
// Storage types for the backend models: same contracts, with MongoDB value types.
const forDb = structuredClone(forTs);
forDb.definitions.ObjectId = { tsType: 'Types.ObjectId' };
forDb.definitions.DateTime = { tsType: 'Date' };
const dbTs = await compile(forDb, 'StoredDomain', { bannerComment: '', unreachableDefinitions: true, additionalProperties: false, strictIndexSignatures: false });
await write('../../backend/src/models/stored.generated.ts', `${banner}// Storage shapes for Mongoose models: ObjectId and DateTime become MongoDB value types.\nimport type { Types } from 'mongoose';\nimport type { OrgType, Role } from '@pitchprism/contracts';\n\n${dbTs}`);
await write('src/schemas.generated.ts',`${banner}export const COLLECTIONS = ${JSON.stringify(collections, null, 2)} as const;\nexport type EntityName = keyof typeof COLLECTIONS;\nexport const domainSchema: { $schema: string; $id: string; title: string; definitions: Record<string, Record<string, unknown>> } =${JSON.stringify(bundle, null, 2)};\n`);

// Python: TypedDicts plus the bundled schema for jsonschema validation in the worker (no extra dependency).
const pyName = name => name.replace(/[^A-Za-z0-9_]/g, '_');
const literalAliases = [];
const typedDicts = [];
function pyType(node, ownerName, prop) {
  if (node.$ref) {
    const name = node.$ref.replace('#/definitions/', '');
    return definitions[name].type === 'object' && definitions[name].properties ? `"${name}"` : name;
  }
  // Functional TypedDict evaluates its values at import time. A quoted forward reference cannot use
  // the | operator ("PortfolioRank" | None); typing.Union accepts forward references safely.
  if (node.anyOf) return `Union[${node.anyOf.map(option => pyType(option, ownerName, prop)).join(', ')}]`;
  if (node.enum) return `Literal[${node.enum.map(v => JSON.stringify(v)).join(', ')}]`;
  switch (node.type) {
    case 'string': return 'str';
    case 'integer': return 'int';
    case 'number': return 'float';
    case 'boolean': return 'bool';
    case 'null': return 'None';
    case 'array': return `list[${pyType(node.items ?? {}, ownerName, prop)}]`;
    case 'object':
      if (node.properties) { const name = node.title ?? `${ownerName}${prop[0].toUpperCase()}${prop.slice(1)}`; emitTypedDict(name, node); return `"${name}"`; }
      if (node.additionalProperties && typeof node.additionalProperties === 'object') return `dict[str, ${pyType(node.additionalProperties, ownerName, prop)}]`;
      return 'dict[str, Any]';
    default: return 'Any';
  }
}
const emitted = new Set();
function emitTypedDict(name, node) {
  if (emitted.has(name)) return;
  emitted.add(name);
  const required = new Set(node.required ?? []);
  const fields = Object.entries(node.properties).map(([prop, schema]) => {
    const type = pyType(schema, name, prop);
    return `    ${JSON.stringify(prop)}: ${required.has(prop) ? `Required[${type}]` : type},`;
  });
  typedDicts.push(`${pyName(name)} = TypedDict(${JSON.stringify(name)}, {\n${fields.join('\n')}\n}, total=False)`);
}
for (const [name, node] of Object.entries(definitions)) {
  if (node.type === 'object' && node.properties) emitTypedDict(name, node);
  else literalAliases.push(`${pyName(name)} = ${pyType(node, name, name)}`);
}
await write('../../ai/contracts/domain.schema.json', `${JSON.stringify(bundle, null, 2)}\n`);
await write('../../ai/contracts/generated.py', `# Generated by packages/contracts/scripts/generate.mjs from packages/contracts/schemas/. Do not edit.
# ObjectId and DateTime are strings in JSON form; documents read from MongoDB carry bson ObjectId and datetime values.
from typing import Any, Literal, Required, TypedDict, Union

${literalAliases.join('\n')}

${typedDicts.join('\n\n')}

COLLECTIONS: dict[str, str] = ${JSON.stringify(collections, null, 4)}
`);
console.log(`Generated ${Object.keys(definitions).length} definitions, ${Object.keys(collections).length} collections.`);
